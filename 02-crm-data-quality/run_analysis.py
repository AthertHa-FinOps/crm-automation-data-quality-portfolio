"""Loads the CSVs into SQLite, runs sql/queries.sql, writes discrepancy-report.md and data/crm_clean.csv."""
import csv, re, sqlite3
db = sqlite3.connect(":memory:")
def load(name, path):
    rows = list(csv.DictReader(open(path)))
    cols = list(rows[0]); db.execute(f"CREATE TABLE {name} ({','.join(cols)})")
    db.executemany(f"INSERT INTO {name} VALUES ({','.join('?'*len(cols))})", [tuple(r[c] for c in cols) for r in rows])
    return rows
src = load("source", "data/source_leads.csv"); crm = load("crm", "data/crm_export.csv")
queries = [q.strip() for q in open("sql/queries.sql").read().split("\n\n") if q.strip() and not q.strip().startswith("-- Tables")]
titles, results = [], []
for q in queries:
    lines = q.splitlines()
    t = next(l for l in lines if l.startswith("-- Q"))[3:]
    sql = "\n".join(l for l in lines if not l.startswith("--")).rstrip(";")
    titles.append(t); results.append(db.execute(sql).fetchall())

# ---- cleaning ----
def norm_phone(p):
    d = re.sub(r"\D", "", p); d = d[1:] if len(d) == 11 and d[0] == "1" else d
    return f"{d[:3]}-{d[3:6]}-{d[6:]}" if len(d) == 10 else p
def valid(e): return bool(re.fullmatch(r"[^@\s]+@[^@\s]+\.[^@\s]+", e))
clean, review, seen = [], [], {}
for r in sorted(crm, key=lambda r: r["created_date"]):
    r = dict(r); r["email"] = r["email"].strip().lower(); r["phone"] = norm_phone(r["phone"].strip())
    r["province"] = "ON" if r["province"].strip().lower().startswith("on") else r["province"]
    r["lead_source"] = r["lead_source"] or "UNKNOWN"
    r["review_flag"] = "" if valid(r["email"]) else ("MISSING_EMAIL" if not r["email"] else "INVALID_EMAIL")
    if r["email"]:
        if r["email"] in seen: review.append(r); continue     # duplicate (even if email invalid) -> dropped, earliest kept
        seen[r["email"]] = r
    clean.append(r)
cols = list(clean[0])
with open("data/crm_clean.csv","w",newline="") as f:
    w = csv.DictWriter(f, fieldnames=cols); w.writeheader(); w.writerows(clean)

# ---- after-cleaning re-check ----
db.execute("DELETE FROM crm")
db.executemany("INSERT INTO crm VALUES (?,?,?,?,?,?,?,?,?)", [tuple(r[c] for c in cols[:9]) for r in clean])
after = [len(db.execute(sql).fetchall()) for sql in (
 "SELECT 1 FROM crm WHERE TRIM(email)<>'' GROUP BY LOWER(TRIM(email)) HAVING COUNT(*)>1",
 "SELECT 1 FROM crm WHERE TRIM(email)=''",
 "SELECT 1 FROM crm WHERE TRIM(email)<>'' AND (TRIM(email) NOT LIKE '%_@_%._%' OR TRIM(email) LIKE '%@@%')",
 "SELECT 1 FROM crm WHERE TRIM(email)<>'' AND email<>LOWER(TRIM(email))",
 "SELECT 1 FROM crm WHERE phone NOT GLOB '[0-9][0-9][0-9]-[0-9][0-9][0-9]-[0-9][0-9][0-9][0-9]'",
 "SELECT 1 FROM crm WHERE province<>'ON'",
 "SELECT 1 FROM crm WHERE TRIM(lead_source)=''")]

# counts: Q6 is grouped, so sum records
def count(i): return sum(r[1] for r in results[i]) if i == 5 else len(results[i])
dup_extra = sum(r[1]-1 for r in results[0])
out = ["# Discrepancy Report — Synthetic CRM Export vs Source Leads", "",
 "All data is **fictional**, generated by `generate_data.py` (seed 42). Every figure below was produced by running `run_analysis.py` on that data.", "",
 f"- Source leads: **{len(src)}**  |  CRM export rows: **{len(crm)}**  |  CRM rows after cleaning: **{len(clean)}**", "",
 "## Findings (before cleaning)", "", "| # | Check | Records affected | Re-check after cleaning |", "|---|---|---|---|"]
aft = {0:after[0],1:after[1],2:after[2],3:after[3],4:after[4],5:after[5],6:after[6]}
for i, t in enumerate(titles):
    out.append(f"| {i+1} | {t.split(' ',1)[1]} | {count(i)} | {aft[i] if i in aft else 'n/a (needs source system / human)'} |")
out += ["", f"Duplicate groups: {len(results[0])}; surplus duplicate rows to merge: {dup_extra}.", "",
 "## Cleaning rules applied (`run_analysis.py`)", "",
 "1. Trim and lowercase email.", "2. Standardize phone to `NNN-NNN-NNNN`.", "3. Map province variants (`Ontario`, `Ont.`, `on`, `ONT`) to `ON`.",
 "4. Blank lead source → `UNKNOWN` (cannot be recovered without the source system).",
 f"5. Duplicates: keep earliest-created record, drop later ones ({len(review)} rows removed).",
 "6. Missing/invalid email: **not guessed** — kept and flagged in `review_flag` for manual review.", "",
 "## Needs human follow-up (not auto-fixed)", "",
 f"- Source leads absent from CRM: {count(7)} → re-sync or confirm intentionally excluded.",
 f"- CRM records with email but no source lead: {count(8)} → confirm origin (manual entry, other channel).",
 f"- CRM vs source conflicts (last name or phone): {count(9)} → decide which system is authoritative per field.",
 f"- Missing/invalid email: {count(1)+count(2)} → obtain email or archive.", "",
 "## Limitations", "",
 "- Synthetic data with injected errors; real CRMs have messier, less predictable problems.",
 "- Matching is on normalized email only; fuzzy name/phone matching would catch more duplicates.",
 "- Counts overlap: one record can fail several checks, and a few figures (e.g. source leads missing from CRM) include records whose email was corrupted in the CRM, so they no longer match by email.",
 "- Dedup keeps the earliest record and does not merge field values."]
open("discrepancy-report.md","w").write("\n".join(out))
print("\n".join(out[5:20]))
